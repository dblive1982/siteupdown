def inside(x, y, poly):
    c = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]; xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c

cols = int(360 / CELL)
rows = int((LAT_TOP - LAT_BOT) / CELL)
grid = []
for r in range(rows):
    lat = LAT_TOP - (r + 0.5) * CELL
    runs = []; start = None
    for c in range(cols + 1):
        lon = -180 + (c + 0.5) * CELL
        land = c < cols and any(inside(lon, lat, p) for p in P.values())
        if land and start is None: start = c
        if not land and start is not None:
            runs.append([start, c - start]); start = None
    grid.append(runs)

out = {'cell': CELL, 'cols': cols, 'rows': rows, 'top': LAT_TOP, 'bot': LAT_BOT, 'runs': grid}
